bool win(char player) {
	for (int i = 1;i <= 15;i++) {
		for (int j = 1;j <= 15;j++) {
			if (chess[i][j] == player) {
				//横向
				if (chess[i][j + 1] == player && chess[i][j + 2] == player && chess[i][j + 3] == player && chess[i][j + 4] == player) {
					return true;
				}
				//竖向
				if (chess[i + 1][j] == player && chess[i + 2][j] == player && chess[i + 3][j] == player && chess[i + 4][j] == player) {
					return true;
				}
				//右斜
				if (chess[i + 1][j + 1] == player && chess[i + 2][j + 2] == player && chess[i + 3][j + 3] == player && chess[i + 4][j + 4] == player) {
					return true;
				}
				//左斜
				if (chess[i - 1][j + 1] == player && chess[i - 2][j + 2] == player && chess[i - 3][j + 3] == player && chess[i - 4][j + 4] == player) {
					return true;
				}
			}
		}
	}
	return false;
}

